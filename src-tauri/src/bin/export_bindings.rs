//! Regenerates `src/lib/bindings.ts` from the Rust IPC types. Rust is the source of truth
//! (`IPC-CONTRACT.md`); this binary is the only thing allowed to write that file.
//!
//! `ts-rs`'s own `#[ts(export)]` mechanism writes one file per type under `bindings/`,
//! which doesn't match this project's single-file convention — so instead we call
//! `TS::decl()` for each type ourselves and concatenate. TypeScript interfaces don't need
//! forward declaration, so concatenation order doesn't matter.
//!
//! Run via `npm run gen:bindings`. CI fails the build if this drifts from what's checked
//! in (`git diff --exit-code -- src/lib/bindings.ts`).

use std::fs;
use std::path::PathBuf;
use ts_rs::{Config, TS};
use vibe_hardware_lib::commands::doctor::ToolchainTool;
use vibe_hardware_lib::commands::settings::GlobalSettingsPatch;
use vibe_hardware_lib::core::claude::ids::{SessionId, TurnId};
use vibe_hardware_lib::core::claude::session::{SessionIndex, SessionIndexEntry, TurnRecord, TurnResultMeta, TurnToolCall};
use vibe_hardware_lib::core::claude::types::{ChatEvent, PermissionPolicy, TurnRequest};
use vibe_hardware_lib::core::pio::boards::{BoardBrief, BoardSource};
use vibe_hardware_lib::core::pio::init::CreateProjectRequest;
use vibe_hardware_lib::core::proc::events::{Defect, DefectSource, ProcEvent, Severity, SizeUsage};
use vibe_hardware_lib::core::proc::{LogLine, ProcId, ProcKind, ProcSummary, StdStream};
use vibe_hardware_lib::core::project::types::{
    CreatedBy, DeviceSettings, ProjectClaudeSettings, ProjectEntry, ProjectPipelineSettings, ProjectSettings,
    StickyHwid, TrustScan,
};
use vibe_hardware_lib::core::settings::{
    AdvancedSettings, AppearanceSettings, ClaudeSettings, EditorSettings, GlobalSettings, LogSettings,
    MonitorSettings, NetworkSettings, PermissionPolicySetting, PipelinePolicySetting, PipelineSettings,
    ThemeSetting, ToolchainSettings,
};
use vibe_hardware_lib::core::snapshot::types::{ChangeStatus, FileChange, FileDiff, SnapshotId};
use vibe_hardware_lib::core::toolchain::install::{InstallEvent, InstallPlan};
use vibe_hardware_lib::core::toolchain::types::{DoctorReport, ProbeResult, Remediation, RemediationKind};
use vibe_hardware_lib::error::{AppError, PermissionDenial};

fn main() {
    // Epoch-millisecond timestamps fit safely in `number` for millennia; `bigint` (ts-rs's
    // default for u64) would force awkward `BigInt` literals on every frontend read.
    let cfg = Config::new().with_large_int("number");
    let mut out = String::new();
    out.push_str("// AUTO-GENERATED by `npm run gen:bindings` — do not edit by hand.\n");
    out.push_str("// Source of truth: src-tauri/src/error.rs and src-tauri/src/core/**.\n\n");

    macro_rules! emit {
        ($ty:ty) => {
            // `decl()` already returns a complete, semicolon-terminated `type X = ...;`.
            out.push_str("export ");
            out.push_str(&<$ty as TS>::decl(&cfg));
            out.push_str("\n\n");
        };
    }

    emit!(ProcId);
    emit!(ProcKind);
    emit!(StdStream);
    emit!(LogLine);
    emit!(ProcSummary);
    emit!(PermissionDenial);
    emit!(AppError);

    // Doctor & toolchain (IPC-CONTRACT.md §2)
    emit!(ProbeResult);
    emit!(RemediationKind);
    emit!(Remediation);
    emit!(DoctorReport);
    emit!(InstallEvent);
    emit!(InstallPlan);
    emit!(ToolchainTool);

    // Settings (IPC-CONTRACT.md §9 / DATA-MODEL.md §3)
    emit!(ToolchainSettings);
    emit!(PermissionPolicySetting);
    emit!(ClaudeSettings);
    emit!(PipelinePolicySetting);
    emit!(PipelineSettings);
    emit!(MonitorSettings);
    emit!(LogSettings);
    emit!(EditorSettings);
    emit!(ThemeSetting);
    emit!(AppearanceSettings);
    emit!(NetworkSettings);
    emit!(AdvancedSettings);
    emit!(GlobalSettings);
    emit!(GlobalSettingsPatch);

    // Pipeline events, shared by project_create (M2) and the build pipeline (M5)
    // (IPC-CONTRACT.md §5)
    emit!(Severity);
    emit!(DefectSource);
    emit!(Defect);
    emit!(SizeUsage);
    emit!(ProcEvent);

    // Projects (IPC-CONTRACT.md §3)
    emit!(BoardSource);
    emit!(BoardBrief);
    emit!(CreateProjectRequest);
    emit!(ProjectEntry);
    emit!(CreatedBy);
    emit!(StickyHwid);
    emit!(DeviceSettings);
    emit!(ProjectClaudeSettings);
    emit!(ProjectPipelineSettings);
    emit!(ProjectSettings);
    emit!(TrustScan);

    // Snapshots and changes (IPC-CONTRACT.md §8)
    emit!(SnapshotId);
    emit!(ChangeStatus);
    emit!(FileChange);
    emit!(FileDiff);

    // Claude turns (IPC-CONTRACT.md §4)
    emit!(serde_json::Value); // -> "JsonValue", referenced by ChatEvent/TurnRecord fields
    emit!(TurnId);
    emit!(SessionId);
    emit!(PermissionPolicy);
    emit!(TurnRequest);
    emit!(ChatEvent);
    emit!(TurnToolCall);
    emit!(TurnResultMeta);
    emit!(TurnRecord);
    emit!(SessionIndexEntry);
    emit!(SessionIndex);

    // Resolved from `CARGO_MANIFEST_DIR` (always `src-tauri/`), not the process's current
    // directory — `npm run gen:bindings` invokes this via `cargo run --manifest-path`,
    // which builds from that manifest but does not `cd` into it first.
    let dest: PathBuf = [env!("CARGO_MANIFEST_DIR"), "..", "src", "lib", "bindings.ts"]
        .iter()
        .collect();
    fs::write(&dest, out).unwrap_or_else(|e| {
        panic!("writing {}: {e}", dest.display());
    });
    println!("wrote {}", dest.display());
}
